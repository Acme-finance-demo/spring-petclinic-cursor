CREATE TABLE IF NOT EXISTS appointments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id INTEGER NOT NULL,
  vet_id INTEGER NOT NULL,
  appointment_date TIMESTAMP NOT NULL,
  reason VARCHAR(255) NOT NULL,
  status VARCHAR(50) DEFAULT 'SCHEDULED',
  FOREIGN KEY (pet_id) REFERENCES pets(id),
  FOREIGN KEY (vet_id) REFERENCES vets(id)
);

CREATE INDEX IF NOT EXISTS appointments_pet_id ON appointments(pet_id);
CREATE INDEX IF NOT EXISTS appointments_vet_id ON appointments(vet_id);
CREATE INDEX IF NOT EXISTS appointments_date ON appointments(appointment_date);
