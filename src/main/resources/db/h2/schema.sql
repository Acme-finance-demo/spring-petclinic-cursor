DROP TABLE vet_holidays IF EXISTS;
DROP TABLE vet_schedules IF EXISTS;
DROP TABLE appointments IF EXISTS;
DROP TABLE vet_specialties IF EXISTS;
DROP TABLE vets IF EXISTS;
DROP TABLE specialties IF EXISTS;
DROP TABLE visits IF EXISTS;
DROP TABLE pets IF EXISTS;
DROP TABLE types IF EXISTS;
DROP TABLE owners IF EXISTS;


CREATE TABLE vets (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name VARCHAR(30),
  last_name  VARCHAR(30)
);
CREATE INDEX vets_last_name ON vets (last_name);

CREATE TABLE specialties (
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80)
);
CREATE INDEX specialties_name ON specialties (name);

CREATE TABLE vet_specialties (
  vet_id       INTEGER NOT NULL,
  specialty_id INTEGER NOT NULL
);
ALTER TABLE vet_specialties ADD CONSTRAINT fk_vet_specialties_vets FOREIGN KEY (vet_id) REFERENCES vets (id);
ALTER TABLE vet_specialties ADD CONSTRAINT fk_vet_specialties_specialties FOREIGN KEY (specialty_id) REFERENCES specialties (id);

CREATE TABLE types (
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80)
);
CREATE INDEX types_name ON types (name);

CREATE TABLE owners (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name VARCHAR(30),
  last_name  VARCHAR_IGNORECASE(30),
  address    VARCHAR(255),
  city       VARCHAR(80),
  telephone  VARCHAR(20)
);
CREATE INDEX owners_last_name ON owners (last_name);

CREATE TABLE pets (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(30),
  birth_date DATE,
  type_id    INTEGER NOT NULL,
  owner_id   INTEGER
);
ALTER TABLE pets ADD CONSTRAINT fk_pets_owners FOREIGN KEY (owner_id) REFERENCES owners (id);
ALTER TABLE pets ADD CONSTRAINT fk_pets_types FOREIGN KEY (type_id) REFERENCES types (id);
CREATE INDEX pets_name ON pets (name);

CREATE TABLE visits (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id      INTEGER,
  visit_date  DATE,
  description VARCHAR(255)
);
ALTER TABLE visits ADD CONSTRAINT fk_visits_pets FOREIGN KEY (pet_id) REFERENCES pets (id);
CREATE INDEX visits_pet_id ON visits (pet_id);

CREATE TABLE appointments (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id           INTEGER NOT NULL,
  vet_id           INTEGER NOT NULL,
  appointment_date DATE NOT NULL,
  appointment_time TIME NOT NULL,
  duration_minutes INTEGER DEFAULT 30,
  reason           VARCHAR(255),
  symptoms         CLOB,
  status           VARCHAR(20) DEFAULT 'PENDING',
  notes            CLOB,
  created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
ALTER TABLE appointments ADD CONSTRAINT fk_appointments_pets FOREIGN KEY (pet_id) REFERENCES pets (id);
ALTER TABLE appointments ADD CONSTRAINT fk_appointments_vets FOREIGN KEY (vet_id) REFERENCES vets (id);
CREATE INDEX appointments_pet_id ON appointments (pet_id);
CREATE INDEX appointments_vet_id ON appointments (vet_id);
CREATE INDEX appointments_date ON appointments (appointment_date);
CREATE INDEX appointments_status ON appointments (status);

CREATE TABLE vet_schedules (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vet_id       INTEGER NOT NULL,
  day_of_week  INTEGER NOT NULL,
  start_time   TIME NOT NULL,
  end_time     TIME NOT NULL,
  is_available BOOLEAN DEFAULT TRUE
);
ALTER TABLE vet_schedules ADD CONSTRAINT fk_vet_schedules_vets FOREIGN KEY (vet_id) REFERENCES vets (id);
CREATE INDEX vet_schedules_vet_id ON vet_schedules (vet_id);
CREATE INDEX vet_schedules_day_of_week ON vet_schedules (day_of_week);

CREATE TABLE vet_holidays (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vet_id       INTEGER NOT NULL,
  holiday_date DATE NOT NULL,
  reason       VARCHAR(255)
);
ALTER TABLE vet_holidays ADD CONSTRAINT fk_vet_holidays_vets FOREIGN KEY (vet_id) REFERENCES vets (id);
CREATE INDEX vet_holidays_vet_id ON vet_holidays (vet_id);
CREATE INDEX vet_holidays_date ON vet_holidays (holiday_date);
