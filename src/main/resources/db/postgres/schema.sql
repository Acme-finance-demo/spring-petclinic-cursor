CREATE TABLE IF NOT EXISTS vets (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name TEXT,
  last_name  TEXT
);
CREATE INDEX ON vets (last_name);

CREATE TABLE IF NOT EXISTS specialties (
  id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT
);
CREATE INDEX ON specialties (name);

CREATE TABLE IF NOT EXISTS vet_specialties (
  vet_id       INT NOT NULL REFERENCES vets (id),
  specialty_id INT NOT NULL REFERENCES specialties (id),
  UNIQUE (vet_id, specialty_id)
);

CREATE TABLE IF NOT EXISTS types (
  id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT
);
CREATE INDEX ON types (name);

CREATE TABLE IF NOT EXISTS owners (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name TEXT,
  last_name  TEXT,
  address    TEXT,
  city       TEXT,
  telephone  TEXT
);
CREATE INDEX ON owners (last_name);

CREATE TABLE IF NOT EXISTS pets (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT,
  birth_date DATE,
  type_id    INT NOT NULL REFERENCES types (id),
  owner_id   INT REFERENCES owners (id)
);
CREATE INDEX ON pets (name);
CREATE INDEX ON pets (owner_id);

CREATE TABLE IF NOT EXISTS visits (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id      INT REFERENCES pets (id),
  visit_date  DATE,
  description TEXT
);
CREATE INDEX ON visits (pet_id);

CREATE TABLE IF NOT EXISTS appointments (
  id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id           INT NOT NULL REFERENCES pets (id),
  vet_id           INT NOT NULL REFERENCES vets (id),
  appointment_date DATE NOT NULL,
  appointment_time TIME NOT NULL,
  duration_minutes INT DEFAULT 30,
  reason           TEXT,
  symptoms         TEXT,
  status           TEXT DEFAULT 'PENDING',
  notes            TEXT,
  created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ON appointments (pet_id);
CREATE INDEX ON appointments (vet_id);
CREATE INDEX ON appointments (appointment_date);
CREATE INDEX ON appointments (status);

CREATE TABLE IF NOT EXISTS vet_schedules (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vet_id       INT NOT NULL REFERENCES vets (id),
  day_of_week  INT NOT NULL,
  start_time   TIME NOT NULL,
  end_time     TIME NOT NULL,
  is_available BOOLEAN DEFAULT TRUE
);
CREATE INDEX ON vet_schedules (vet_id);
CREATE INDEX ON vet_schedules (day_of_week);

CREATE TABLE IF NOT EXISTS vet_holidays (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vet_id       INT NOT NULL REFERENCES vets (id),
  holiday_date DATE NOT NULL,
  reason       TEXT
);
CREATE INDEX ON vet_holidays (vet_id);
CREATE INDEX ON vet_holidays (holiday_date);
